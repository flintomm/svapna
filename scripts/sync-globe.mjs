#!/usr/bin/env node
// Brings a build of the Globe of Thought atlas (github.com/flintomm/Globe-of-Thought) into this site.
//
//   node scripts/sync-globe.mjs [path to the atlas repository's dist/ folder]
//
// The atlas ships as a stand-alone dark page. Here it is one section of Svapna, so this script:
//   1. copies its scripts and data to public/globe-of-thought/
//   2. extracts the page body (without the atlas's own masthead and footer) to src/generated/globe-of-thought.html
//   3. rewrites its stylesheet so every rule applies only inside `.atlas`, and turns its dark palette into
//      black on white, as public/globe-of-thought/atlas.css
// The Svapna look itself (type, hairlines, square markers) is hand-written in public/globe-of-thought/theme.css.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.resolve(process.argv[2] || path.join(root, '..', 'Globe-of-Thought', 'dist'));
const out = path.join(root, 'public', 'globe-of-thought');
if (!fs.existsSync(path.join(dist, 'app.js'))) {
  console.error(`No atlas build at ${dist}. Pass the path to the atlas repository's dist/ folder.`);
  process.exit(1);
}
fs.mkdirSync(out, { recursive: true });
fs.mkdirSync(path.join(root, 'src', 'generated'), { recursive: true });

// 1. scripts and data, unchanged
for (const file of ['app.js', 'evidence.js', 'land.js', 'd3.min.js', 'third-party.txt']) {
  fs.copyFileSync(path.join(dist, file), path.join(out, file));
}

// 2. page body
const html = fs.readFileSync(path.join(dist, 'index.html'), 'utf8');
const main = html.slice(html.indexOf('<main>') + 6, html.indexOf('</main>'));
const body = main
  .replace(/<header class="mast">[\s\S]*?<\/header>/, '')
  .replace(/<footer>[\s\S]*?<\/footer>/, '')
  .trim();
if (!body.includes('id="passage"')) throw new Error('The atlas page no longer has the expected structure.');
fs.writeFileSync(path.join(root, 'src', 'generated', 'globe-of-thought.html'), body + '\n');

// 3. stylesheet, scoped and inverted
const scopeSelector = selector => {
  const s = selector.trim();
  if (/^(:root|html|body|main|\*)$/.test(s)) return s === '*' ? '.atlas *' : '.atlas';
  return '.atlas ' + s;
};
// Walks the stylesheet one block at a time. Media queries are scoped inside; other at-rules pass through.
function scope(css) {
  let result = '', i = 0;
  while (i < css.length) {
    const open = css.indexOf('{', i);
    if (open < 0) { result += css.slice(i); break; }
    let depth = 1, close = open + 1;
    while (depth && close < css.length) { if (css[close] === '{') depth++; else if (css[close] === '}') depth--; close++; }
    const head = css.slice(i, open), block = css.slice(open + 1, close - 1);
    const comments = (head.match(/\/\*[\s\S]*?\*\//g) || []).join('\n');
    const selector = head.replace(/\/\*[\s\S]*?\*\//g, '').trim();
    if (selector.startsWith('@media')) result += `${comments}\n${selector} {${scope(block)}}\n`;
    else if (selector.startsWith('@')) result += `${comments}\n${selector} {${block}}\n`;
    else if (!/^(footer|\.mast|\.wordmark|\.orbmark|\.edition|\.rule)\b/.test(selector)) {
      result += `${comments}\n${selector.split(',').map(scopeSelector).join(', ')} {${block}}\n`;
    }
    i = close;
  }
  return result;
}
// Light becomes dark and dark becomes light, in greys: the atlas's navy and gold turn into Svapna's black on white.
const invert = hex => {
  let h = hex.slice(1);
  if (h.length === 3) h = [...h].map(c => c + c).join('');
  const [r, g, b] = [0, 2, 4].map(k => parseInt(h.slice(k, k + 2), 16) / 255);
  const light = 1 - (0.2126 * r + 0.7152 * g + 0.0722 * b);
  const grey = light >= 0.5 ? 1 - (1 - light) * 0.45 : light * 0.8;
  const v = Math.round(grey * 255).toString(16).padStart(2, '0');
  return '#' + v + v + v + h.slice(6);
};
const base = fs.readFileSync(path.join(dist, 'style.css'), 'utf8');
const scoped = scope(base).replace(/#[0-9a-fA-F]{8}\b|#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b/g, invert);
fs.writeFileSync(path.join(out, 'atlas.css'),
  '/* Generated by scripts/sync-globe.mjs from the atlas stylesheet. Do not edit; see theme.css. */\n' + scoped);


// A slim copy of the passages for the home experience: only what it shows, about a third of the full file.
{
  const raw = fs.readFileSync(path.join(out, 'evidence.js'), 'utf8');
  const atlas = JSON.parse(raw.slice(raw.indexOf('{'), raw.lastIndexOf('}') + 1));
  const slim = {
    questions: atlas.questions.map(q => ({ id: q.id, question: q.question, scale: q.scale.map(({ id, label, tone }) => ({ id, label, tone })) })),
    cards: atlas.cards.map(c => ({ id: c.id, name: c.name, excerpt: c.excerpt, ...(c.translation ? { translation: c.translation } : {}), place: c.place, dateShort: c.dateShort,
      sortYear: c.sortYear, work: c.work, lat: c.lat, lng: c.lng, sourceUrl: c.sourceUrl, readings: Object.fromEntries(Object.entries(c.readings).map(([k, v]) => [k, { score: v.score }])) })),
  };
  const dir = path.join(out, '..', 'next');
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'data.js'), '// Generated by scripts/sync-globe.mjs. Do not edit.\nwindow.PILOT_EVIDENCE = ' + JSON.stringify(slim) + ';\n');
}

const count = (fs.readFileSync(path.join(out, 'evidence.js'), 'utf8').match(/"sourceUrl"/g) || []).length;
console.log(`Synced Globe of Thought from ${dist}: ${count} passages.`);
